#!/usr/bin/env python3
"""Writes THIRD-PARTY.md: bundled fonts and every crate compiled into
forhunt-viewer with its licence (from `cargo metadata`).

usage: python3 scripts/third-party.py
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(p["id"] for p in meta["packages"] if p["name"] == "fhv-app")

# Normal (non-dev, non-build) dependencies reachable from the app, any target.
seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
            stack.append(d["pkg"])

rows = sorted((pkgs[i]["name"], pkgs[i]["version"], pkgs[i].get("license") or "?",
               pkgs[i].get("repository") or "") for i in seen
              if pkgs[i]["name"] not in ("fhv-app", "fhv-engine"))
out = ["# Third-party software", "",
       "forhunt-viewer is MIT OR Apache-2.0. It bundles:", "",
       "## Fonts", "",
       "- Inter 4.001, SIL Open Font License 1.1 (crates/fhv-app/assets/fonts/OFL-Inter.txt)",
       "- JetBrains Mono 2.211, SIL Open Font License 1.1 (crates/fhv-app/assets/fonts/OFL-JetBrainsMono.txt)",
       "",
       "## Rust crates", "",
       "Generated by scripts/third-party.py; `cargo deny check licenses` enforces the allowed list (deny.toml).",
       "Some are platform-specific and only in the build for that OS.", "",
       "| Crate | Version | Licence | Source |", "|---|---|---|---|"]
out += [f"| {n} | {v} | {l} | {r} |" for n, v, l, r in rows]
(ROOT / "THIRD-PARTY.md").write_text("\n".join(out) + "\n")
print(f"THIRD-PARTY.md: {len(rows)} crates")
